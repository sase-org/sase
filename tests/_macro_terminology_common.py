def iter_scope_files(suffix: str | None = None) -> list[Path]:
    found: list[Path] = []
    for scope in (Path("src"), Path("tests")):
        root = ROOT / scope
        candidates = sorted(root.rglob(f"*{suffix}" if suffix else "*"))
        for path in candidates:
            if not path.is_file():
                continue
            if "__pycache__" in path.parts:
                # Generated bytecode mirrors source names; never source.
                continue
            found.append(path)
    return found


def literal_key(line: str) -> str:
    return line.strip()[:200]
