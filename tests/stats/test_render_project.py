GOLDEN = Path(__file__).parent / "golden" / "render"
_UPDATE = os.environ.get("SASE_UPDATE_PROJECT_RENDER_GOLDENS") == "1"


def _export(renderable, ctx: RenderContext) -> str:
    # Pin height as well as width: pytest-xdist workers export LINES, and Rich
    # then treats both dimensions as explicit and subtracts 1 when
    # legacy_windows is true. The renderer already honors ctx.unicode for
    # glyphs and box style, so the capture console stays non-legacy.
    console = Console(
        width=ctx.width,
        height=256,
        color_system="truecolor" if ctx.color else None,
        no_color=not ctx.color,
        force_terminal=True,
        highlight=False,
        record=True,
        legacy_windows=False,
        file=StringIO(),
        emoji=ctx.unicode,
    )
    console.print(renderable)
    return console.export_text(styles=False)


def _assert_golden(name: str, actual: str) -> None:
    path = GOLDEN / name
    if _UPDATE:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            actual if actual.endswith("\n") else actual + "\n", encoding="utf-8"
        )
        return
    expected = path.read_text(encoding="utf-8")
    assert actual == expected


def test_render_context_from_console_is_injectable() -> None:
    console = Console(width=100, color_system=None, force_terminal=True)
    ctx = RenderContext.from_console(console, now=NOW, machine="pinned")
    assert ctx.width == 100
    assert ctx.color is False
    assert ctx.now == NOW.astimezone(ctx.timezone)
    assert ctx.machine == "pinned"
    assert ctx.show_detail_columns
    assert not ctx.stacked


