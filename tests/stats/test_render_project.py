def test_eighty_columns_drop_detail_headers() -> None:
    wide = _export(
        render_project_stats(one_project_view(), "model", render_context(width=120)),
        render_context(width=120),
    )
    narrow = _export(
        render_project_stats(one_project_view(), "model", render_context(width=80)),
        render_context(width=80),
    )

    def header(text: str) -> str:
        for line in text.splitlines():
            if "COMMITS" in line and "SHARE" in line:
                return line
        return ""

    assert "EPIC" in header(wide)
    assert "TALE" in header(wide)
    assert "EPIC" not in header(narrow)
    assert "TALE" not in header(narrow)


def test_markdown_escapes_pipes_and_has_no_ansi() -> None:
    view = one_project_view()
    object.__setattr__(view.projects[0], "label", "sase | `x`")
    markdown = render_project_stats_markdown(
        view,
        "project",
        command_line="sase stats project -p sase",
        versions={"sase": "0.1", "sase_core": "0.2"},
        ctx=render_context(width=120),
    )
    assert "\x1b" not in markdown
    assert "sase \\| \\`x\\`" in markdown
    assert markdown.endswith("\n")
    assert "Generated by `sase stats project -p sase`" in markdown


