"""Frozen reference composer for the virtual body line model.

Copied verbatim from the pre-virtualization ``compose_body`` /
``_paint_section_body`` / ``apply_gutter`` pipeline (with section-rule,
label-capsule and mark rendering) and frozen: every src helper a later
phase might delete or change is vendored here under test-only names, so
later refactors cannot silently move the oracle. Stable leaves (the
document model, link-kind tables, trail text) are still imported live.

Do not edit this file. If a parity test fails after a src change, the src
change moved rendering — that is the signal, not an excuse to update the
oracle.
"""

